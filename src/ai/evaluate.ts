const TABLES: Partial<Record<PieceType, number[]>> = {
  P: PAWN, N: KNIGHT, B: BISHOP, R: ROOK, Q: QUEEN, M: KNIGHT, C: KNIGHT,
};

const tableIndex = (piece: Piece, s: number): number =>
  piece.color === 'w' ? (7 - rankOf(s)) * 8 + fileOf(s) : rankOf(s) * 8 + fileOf(s);

function positional(piece: Piece, endgame: boolean): number {
  if (piece.type === 'K') {
    const t = endgame ? KING_END : KING_MID;
    return t[tableIndex(piece, piece.squares[0])];
  }
  const t = TABLES[piece.type];
  if (!t) return 0;
  let sum = 0;
  for (const s of piece.squares) sum += t[tableIndex(piece, s)];
  return sum / piece.squares.length;
}

/** Static evaluation in centipawns from the side-to-move's point of view. */
export function evaluate(st: GameState): number {
  let heavy = 0;
  for (const p of st.pieces.values()) {
    if (p.type !== 'P' && p.type !== 'K') heavy += PIECES[p.type].value;
  }
  const endgame = heavy <= 2600;
  let score = 0;
  for (const p of st.pieces.values()) {
    const v = PIECES[p.type].value + positional(p, endgame);
    score += p.color === 'w' ? v : -v;
  }
  return st.turn === 'w' ? score : -score;
}
